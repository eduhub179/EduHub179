"""Тип материала по имени файла — бесплатно и без модели.

Покрывает то, что реально пишут в именах: ДЗ-15, КР-2, лист 16, конспект 3, самостоятельная.
Если имя ничего не говорит — возвращаем None и «none», дальше решает модель. Порядок проверок
важен: «Листок 16. Самостоятельная работа» — это самостоятельная, а не листок.

Что важно не перепутать (правки Макса 19.10):
  * «задачник» — это учебник, а не листок;
  * «плюсник» — таблица с результатами, отдельный тип plusnik_sheet, а не worksheet;
  * «вариант» — обычно самостоятельная или контрольная; без контекста это medium,
    поэтому модель всё равно посмотрят.
"""
import re

# (тип, уверенность, слова). Более сильные правила идут раньше.
RULES = [
    ("homework", "high", ["домашнее задание", "домашняя работа", "домашка", "дз"]),
    ("test", "high", ["контрольная работа", "контрольная", "проверочная", "зачет", "зачёт",
                      "экзамен", "тест", "кр"]),
    ("independent_work", "high", ["самостоятельная работа", "самостоятельная", "самост",
                                  "отработка", "ср"]),
    ("lab", "high", ["лабораторная работа", "лабораторная", "лабораторка", "практикум"]),
    ("notes", "high", ["конспект", "лекция", "урок"]),
    ("textbook", "high", ["учебник", "пособие", "сборник задач", "задачник"]),
    ("plusnik_sheet", "high", ["плюсник", "plusnik"]),
    ("worksheet", "high", ["листок", "лист", "worksheet"]),
    ("presentation", "high", ["презентация", "слайд", "presentation"]),
    ("essay", "high", ["сочинение", "эссе", "изложение", "доклад", "реферат"]),
    ("project", "high", ["проект"]),
    # «вариант 2» без других слов — чаще самостоятельная/контрольная, но не факт:
    # medium заставляет labels.py позвать модель, а не догадываться.
    ("independent_work", "medium", ["вариант"]),
]
PROGRAM_EXT = {".py", ".ipynb", ".js", ".ts", ".java", ".c", ".cpp"}

# Короткие слова ищем только отдельным словом, иначе «кружок» станет контрольной,
# а «листинг» — листком.
SHORT = {"дз", "кр", "ср", "лист"}


def _norm(s):
    return re.sub(r"\s+", " ", (s or "").lower().replace("ё", "е")).strip()


def type_of(name):
    """(тип, уверенность, источник). None — имя ничего не говорит."""
    n = _norm(name)
    if not n:
        return None, "none", None
    for kind, conf, words in RULES:
        for w in words:
            if w in SHORT:
                if re.search(rf"(?<![а-яa-z0-9]){w}(?![а-яa-z0-9])", n):
                    return kind, conf, "name"
            elif w in n:
                return kind, conf, "name"
    ext = "." + name.rsplit(".", 1)[-1].lower() if "." in name else ""
    if ext in PROGRAM_EXT:
        return "program", "high", "ext"
    return None, "none", None
