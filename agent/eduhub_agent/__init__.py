"""EduHub179: агент школы — чаты, вложения, распознавание, отправка в бэкенд."""
import os
import time

# Школа в Москве, а сервер может стоять где угодно (тестовый — в Лондоне). «Сегодня», «завтра», дата сообщения
# и срок домашки везде считаются по местному времени процесса (date.today(), datetime.now(), time.localtime),
# поэтому ставим процессу московское время до импорта остального кода. "MSK-3" = UTC+3 без перехода на летнее
# время (так в Москве с 2014 года); строка работает и без базы часовых поясов. Другой пояс: AGENT_TZ в окружении.
os.environ["TZ"] = os.environ.get("AGENT_TZ") or "MSK-3"
if hasattr(time, "tzset"):  # на Windows tzset нет
    time.tzset()
