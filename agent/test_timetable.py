def main():
    tmp = Path(tempfile.mkdtemp()) / "subs.json"
    tmp.write_text(json.dumps(SUBS, ensure_ascii=False), encoding="utf-8")
    T.SOURCE = T.FileSource(T.FILE, tmp)
    ok = 0
    for chat, typ, sent, text, d, given, due, num, kind in CASES:
        it = {"chat": chat, "type": typ, "sent_at": sent + ":00", "summary": text, "quote": text}
        if d:
            it["date"] = d
        T.link(it, text)
        lg, dl = it.get("lesson_given"), it.get("due_lesson")
        got = ((lg["date"], lg["num"]) if lg else None, it.get("date"), dl["num"] if dl else None, it.get("due_kind"))
        good = got[:3] == (given, due, num) and (kind is None or (got[3] or "").startswith(kind))
        ok += good
        print(("✓" if good else "✗"), f"{chat} {sent} «{text}»: задали {T.describe(lg)} | срок {it.get('date')} "
              f"{T.describe(dl)} {it.get('due_kind') or ''}" + ("" if good else f"   ждали {given} {due} урок {num} «{kind}»"))
    print(f"\nВерно {ok} из {len(CASES)}")
    return ok == len(CASES)


if __name__ == "__main__":
    sys.exit(0 if main() else 1)
